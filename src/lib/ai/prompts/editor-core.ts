export const EDITOR_CORE_VERSION = "editor-core@1.1";

/** Вызывается только после детерминированного провала writer-ответа. */
export function editorPrompt(errors: string[]): string {
  return `Исправь JSON результата ToxicHR. Верни только JSON той же структуры. Не добавляй новых фактов и не меняй ссылки на findingIds. Исправь только эти нарушения: ${errors.join("; ")}. Сохрани характер, дерзость и точные авторские образы выбранной персоны, если они не нарушают факты. Не превращай локальное исправление в нейтральную перепись всего текста и не добавляй обязательные слова-маркеры.`;
}
