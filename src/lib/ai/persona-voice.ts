/**
 * Блок для system-промпта persona-этапа: голос персонажа + имя кандидата.
 */
export function voicePromptBlock(
  personaId: PersonaId,
  candidateFirstName?: string | null,
): string {
  const v = VOICE_PROFILES[personaId];
  const name = candidateFirstName?.trim();

  return `ГОЛОС ПЕРСОНАЖА (соблюдать строго):
Роль: ${v.role}.
Обращение: ${v.address}${
    name
      ? ` Имя кандидата — ${name}. Используй его 2–4 раза за весь разбор, в естественных местах (первая фраза, момент нажима, вывод). Не вставляй имя в каждый абзац.`
      : " Имя кандидата неизвестно — обращайся без имени, не выдумывай его."
  }
Регистр: ${v.register}
Ритм и синтаксис: ${v.rhythm}
Словарь-маркеры (вплетай естественно, 5–10 штук за разбор, не подряд): ${v.markers.join(", ")}.
Фирменные ходы (используй 2–3 из них):
${v.moves.map((m) => `- ${m}`).join("\n")}
Этот персонаж никогда:
${v.never.map((n) => `- ${n}`).join("\n")}
Калибровка звучания (НЕ копируй дословно — это образцы тона):
${v.samples.map((s) => `«${s}»`).join("\n")}

ЗАПРЕЩЕНЫ обороты-маркеры ИИ-текста: ${AI_TELLS_FORBIDDEN.join("; ")}.
Пиши как живой человек в устной речи, а не как модель, имитирующая человека.`;
}
